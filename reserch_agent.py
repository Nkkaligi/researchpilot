# ------------------------------------------------------------
# PDF Indexing
# ------------------------------------------------------------
def index_pdf(file_path: Optional[str]) -> str:
    if not file_path:
        return "Please select a PDF file."

    path = Path(file_path)
    if path.suffix.lower() != ".pdf":
        return "Only PDF files are supported."

    size_mb = path.stat().st_size / (1024 * 1024)
    if size_mb > MAX_PDF_SIZE_MB:
        return f"PDF exceeds {MAX_PDF_SIZE_MB} MB limit ({size_mb:.1f} MB)."

    try:
        with pymupdf.open(str(path)) as doc:
            if doc.is_encrypted:
                return "Encrypted PDFs are not supported."
            if len(doc) > MAX_PDF_PAGES:
                return f"PDF exceeds {MAX_PDF_PAGES}-page limit."

            file_hash = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
            documents, metadatas, ids = [], [], []

            for page_num, page in enumerate(doc, start=1):
                text = page.get_text().strip()
                if not text:
                    continue

                words = text.split()
                start = 0
                chunk_idx = 0
                while start < len(words):
                    end = min(start + CHUNK_WORDS, len(words))
                    chunk = " ".join(words[start:end]).strip()
                    if chunk:
                        documents.append(chunk)
                        metadatas.append({
                            "paper": path.name,
                            "page": page_num,
                            "file_hash": file_hash
                        })
                        ids.append(f"{file_hash}_p{page_num}_c{chunk_idx}")
                        chunk_idx += 1
                    if end == len(words):
                        break
                    start = end - CHUNK_OVERLAP

            if not documents:
                return "No extractable text found. The PDF may be image-only (OCR required)."

            embeddings = embedder.encode(
                documents, normalize_embeddings=True, show_progress_bar=False
            ).tolist()

            collection.upsert(
                ids=ids,
                documents=documents,
                metadatas=metadatas,
                embeddings=embeddings
            )

            return (
                f"✓ Indexed {len(documents)} chunks from **{path.name}**. "
                f"Total chunks in database: {collection.count()}"
            )

    except Exception as e:
        return f"PDF indexing failed: {type(e).__name__}: {e}"


# ------------------------------------------------------------
# Local Retrieval (RAG)
# ------------------------------------------------------------
def retrieve_local(question: str, k: int = 5) -> List[Dict[str, Any]]:
    if not question or not question.strip():
        return []

    count = collection.count()
    if count == 0:
        return []

    query_emb = embedder.encode(question, normalize_embeddings=True).tolist()
    results = collection.query(
        query_embeddings=[query_emb],
        n_results=min(k, count),
        include=["documents", "metadatas", "distances"]
    )

    evidence = []
    for text, meta, dist in zip(
        results["documents"][0],
        results["metadatas"][0],
        results["distances"][0]
    ):
        evidence.append({
            "text": text,
            "paper": meta["paper"],
            "page": meta["page"],
            "distance": float(dist)
        })
    return evidence


# ------------------------------------------------------------
# External Search (OpenAlex)
# ------------------------------------------------------------
def search_openalex(topic: str, limit: int = 5) -> List[Dict[str, Any]]:
    topic = (topic or "").strip()
    if not topic:
        return []

    limit = max(1, min(int(limit), 15))
    params = {
        "search": topic,
        "per-page": limit,
        "filter": "from_publication_date:2018-01-01"
    }
    email = os.getenv("OPENALEX_EMAIL")
    if email:
        params["mailto"] = email

    try:
        r = requests.get(
            "https://api.openalex.org/works",
            params=params,
            timeout=25
        )
        r.raise_for_status()
        data = r.json()
    except Exception as e:
        print(f"OpenAlex error: {e}")
        return []

    papers = []
    for work in data.get("results", []):
        authors = []
        for authorship in work.get("authorships", [])[:6]:
            name = authorship.get("author", {}).get("display_name")
            if name:
                authors.append(name)

        papers.append({
            "title": work.get("display_name") or "Untitled",
            "year": work.get("publication_year"),
            "authors": authors,
            "doi": work.get("doi"),
            "openalex_id": work.get("id"),
            "cited_by_count": work.get("cited_by_count", 0)
        })
    return papers


# ------------------------------------------------------------
# Evidence formatting & citation helpers
# ------------------------------------------------------------
def format_local_evidence(local: List[Dict]) -> List[str]:
    blocks = []
    for i, item in enumerate(local, 1):
        blocks.append(
            f"[L{i}] Local PDF – {item['paper']}, page {item['page']}\n"
            f"{item['text']}"
        )
    return blocks


def format_external_evidence(papers: List[Dict]) -> List[str]:
    blocks = []
    for i, p in enumerate(papers, 1):
        authors = ", ".join(p["authors"]) if p["authors"] else "Unknown"
        blocks.append(
            f"[E{i}] External (metadata only)\n"
            f"Title: {p['title']}\n"
            f"Year: {p['year']}\n"
            f"Authors: {authors}\n"
            f"DOI: {p['doi'] or 'N/A'}\n"
            f"Citations: {p['cited_by_count']}\n"
            f"OpenAlex: {p['openalex_id']}\n"
            "NOTE: Only bibliographic metadata is available. "
            "Do not claim specific findings from this paper."
        )
    return blocks


def validate_citations(answer: str, available_ids: List[str]) -> Dict[str, Any]:
    cited = set(re.findall(r"\[([LE]\d+)\]", answer))
    available = set(available_ids)
    missing = cited - available
    malformed = re.findall(r"\[(\d+)\]", answer)  # bare numbers

    return {
        "valid": len(missing) == 0 and len(malformed) == 0 and len(cited) > 0,
        "cited": sorted(cited),
        "available": sorted(available),
        "missing": sorted(missing),
        "malformed": malformed
    }


