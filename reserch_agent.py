# Core research function
# ------------------------------------------------------------
def research(question: str, mode: str = "Combined", api_key: str = "") -> str:
    question = (question or "").strip()
    if not question:
        return "Please enter a research question."

    # A key typed in the UI overrides the saved OPENAI_API_KEY
    api_key = (api_key or "").strip()
    if api_key:
        llm_client = OpenAI(api_key=api_key)
    elif os.getenv("OPENAI_API_KEY"):
        llm_client = client
    else:
        return "No OpenAI API key. Paste your key in the 'OpenAI API key' box."

    evidence_blocks = []
    evidence_ids = []

    # Local RAG
    if mode in ("Local PDF", "Combined"):
        local = retrieve_local(question, k=6)
        for i, item in enumerate(local, 1):
            eid = f"L{i}"
            evidence_ids.append(eid)
            evidence_blocks.append(
                f"[{eid}] Local PDF – {item['paper']}, page {item['page']}\n"
                f"{item['text']}"
            )

    # External OpenAlex
    if mode in ("External Papers", "Combined"):
        papers = search_openalex(question, limit=6)
        for i, p in enumerate(papers, 1):
            eid = f"E{i}"
            evidence_ids.append(eid)
            authors = ", ".join(p["authors"]) if p["authors"] else "Unknown"
            evidence_blocks.append(
                f"[{eid}] External (metadata only)\n"
                f"Title: {p['title']}\n"
                f"Year: {p['year']}\n"
                f"Authors: {authors}\n"
                f"DOI: {p['doi'] or 'N/A'}\n"
                f"Citations: {p['cited_by_count']}\n"
                f"OpenAlex: {p['openalex_id']}\n"
                "NOTE: Only bibliographic metadata is available. "
                "Do not claim specific findings from this paper."
            )

    if not evidence_blocks:
        return (
            "No evidence found.\n\n"
            "• Upload and index at least one PDF for Local / Combined mode.\n"
            "• Or try a broader query for External Papers mode."
        )

    evidence_text = "\n\n".join(evidence_blocks)

    system_prompt = (
        "You are ResearchPilot, a rigorous academic research assistant.\n\n"
        "Rules:\n"
        "1. Base every factual claim strictly on the supplied evidence.\n"
        "2. Cite local text evidence with [L1], [L2], etc.\n"
        "3. Cite external sources with [E1], [E2], etc.\n"
        "4. External sources currently provide only bibliographic metadata. "
        "You may note them as potentially relevant literature, but you must "
        "NOT claim that they support specific scientific findings.\n"
        "5. Never invent authors, titles, results, page numbers, or quotations.\n"
        "6. If the evidence is insufficient, state the limitation clearly.\n"
        "7. Write clear, MSc-level academic prose. Use short headings when helpful."
    )

    user_prompt = (
        f"Research question:\n{question}\n\n"
        f"Available evidence:\n{evidence_text}"
    )

    try:
        response = llm_client.chat.completions.create(
            model=LLM_MODEL,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            temperature=0.2,
            timeout=60
        )
        answer = response.choices[0].message.content or ""
    except Exception as e:
        return f"LLM request failed: {type(e).__name__}: {e}"

    # Citation validation
    check = validate_citations(answer, evidence_ids)
    warning = ""
    if not check["valid"]:
        warning = (
            "\n\n---\n"
            "**Citation warning:** Some citations may be missing or malformed. "
            f"Cited: {check['cited']} | Available: {check['available']} | "
            f"Missing: {check['missing']}"
        )

    references = "\n\n".join(evidence_blocks)

    return (
        answer
        + warning
        + "\n\n---\n\n### Retrieved evidence\n\n"
        + references
    )


